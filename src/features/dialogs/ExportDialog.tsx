import { Braces, Download, FileCode, Globe, Loader2 } from "lucide-react";
import type { LucideIcon } from "lucide-react";
import { useState } from "react";
import { DialogFrame } from "@/components/dialogs/DialogFrame";
import { GhostButton } from "@/components/primitives";
import { getClient } from "@/app/client";
import type { Environment } from "@/daemon/types";
import { downloadJson } from "@/lib/download";
import { useStore } from "@/state/store";
import { cn } from "@/lib/utils";

interface ExportRow {
  id: "postman" | "environments" | "openapi";
  icon: LucideIcon;
  title: string;
  sub: string;
  file: string;
}

/** Postman's environment file shape, one per studio environment. */
function toPostmanEnvironments(envs: Environment[]) {
  return envs.map((env) => ({
    name: env.name,
    values: env.variables.map((v) => ({
      key: v.key,
      value: v.value,
      enabled: v.enabled,
      type: v.type,
    })),
    _postman_variable_scope: "environment",
    _postman_exported_at: new Date().toISOString(),
  }));
}

export function ExportDialog() {
  const popDialog = useStore((s) => s.popDialog);
  const pushToast = useStore((s) => s.pushToast);
  const routeCount = useStore((s) => s.routes.filter((r) => r.protocol === "http").length);
  const environments = useStore((s) => s.environments);
  const projectName = useStore((s) => s.projects.find((p) => p.id === s.activeProjectId)?.name ?? "zestman");
  const [busy, setBusy] = useState<ExportRow["id"] | null>(null);

  const rows: ExportRow[] = [
    {
      id: "postman",
      icon: Braces,
      title: "Postman Collection",
      sub: `${projectName}.postman_collection.json · ${routeCount} requests`,
      file: `${projectName}.postman_collection.json`,
    },
    {
      id: "environments",
      icon: Globe,
      title: "Environments",
      sub: `${environments.length} ${environments.length === 1 ? "environment" : "environments"} · Postman format`,
      file: `${projectName}.postman_environments.json`,
    },
    {
      id: "openapi",
      icon: FileCode,
      title: "OpenAPI",
      sub: "openapi.json · generated by the daemon",
      file: "openapi.json",
    },
  ];

  const download = async (row: ExportRow) => {
    if (busy) return;
    setBusy(row.id);
    try {
      if (row.id === "postman") {
        const exported = (await getClient().exportPostman()) as { collection?: unknown } | null;
        downloadJson(row.file, exported && typeof exported === "object" && "collection" in exported ? exported.collection : exported);
      } else if (row.id === "environments") {
        downloadJson(row.file, toPostmanEnvironments(environments));
      } else {
        downloadJson(row.file, await getClient().getOpenApi());
      }
      pushToast({ kind: "info", text: `Exported ${row.file}` });
    } catch {
      /* the daemon's message is already toasted by the client */
    } finally {
      setBusy(null);
    }
  };

  return (
    <DialogFrame title="Export" width={520} footer={<GhostButton onClick={popDialog}>Close</GhostButton>}>
      <div className="flex flex-col">
        {rows.map((r, i) => (
          <div
            key={r.title}
            style={{ animationDelay: `${i * 40}ms` }}
            className={cn(
              "flex h-14 items-center gap-3 animate-in fade-in-0 fill-mode-both",
              "duration-[var(--dur-base)] ease-[var(--ease-out)]",
              i > 0 && "border-t border-line",
            )}
          >
            <r.icon size={16} strokeWidth={1.5} className="shrink-0 text-ink-2" />
            <div className="min-w-0 flex-1">
              <div className="text-base font-medium text-ink">{r.title}</div>
              <div className="mt-0.5 truncate text-xs text-ink-3">{r.sub}</div>
            </div>
            <GhostButton
              onClick={() => void download(r)}
              disabled={busy != null}
              aria-busy={busy === r.id}
              aria-label={`Download ${r.file}`}
            >
              {busy === r.id ? (
                <Loader2 size={14} strokeWidth={1.5} className="animate-spin" />
              ) : (
                <Download size={14} strokeWidth={1.5} />
              )}
              Download
            </GhostButton>
          </div>
        ))}
      </div>
    </DialogFrame>
  );
}
